#!/usr/bin/env python3
"""Download the DSM worker wheels and write a hash-locked requirements file.

The target is the DS723+ (Synology r1000, DSM 7.2, x86-64) with the
SynoCommunity Python 3.13 package.  Running this on Windows is supported:
pip resolves Linux wheels from the wheel metadata.
"""
from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS = ROOT / 'requirements-dsm.in'
WHEELHOUSE = ROOT / 'wheelhouse'
LOCK = ROOT / 'requirements-dsm.lock'
PLATFORM = 'manylinux2014_x86_64'
PYTHON_VERSION = '313'
FORBIDDEN = ('win', 'macos', 'aarch64', 'armv7l', 'i686', 'musllinux', 'ppc', 's390',
             'riscv64', 'android', 'ios', 'freebsd')
REQUIRED = {'requests', 'pysocks', 'm3u8', 'pillow', 'curl-cffi', 'cffi',
            'certifi', 'charset-normalizer', 'idna', 'urllib3', 'pycparser'}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def wheel_metadata(path: Path) -> tuple[str, str]:
    with zipfile.ZipFile(path) as archive:
        for name in archive.namelist():
            if name.endswith('.dist-info/METADATA'):
                text = archive.read(name).decode('utf-8', errors='replace')
                meta: dict[str, str] = {}
                for line in text.splitlines():
                    if not line.strip():
                        break
                    if ': ' in line:
                        key, value = line.split(': ', 1)
                        meta[key.lower()] = value
                return meta.get('name', ''), meta.get('version', '')
    raise SystemExit(f'No METADATA found in {path.name}')


def validate_wheel(path: Path) -> None:
    name = path.name.lower()
    if any(token in name for token in FORBIDDEN):
        raise SystemExit(f'Wrong platform wheel: {path.name}')
    if not (('cp313' in name) or ('abi3' in name) or name.endswith('py3-none-any.whl')):
        raise SystemExit(f'Wrong Python ABI wheel: {path.name}')


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--keep', action='store_true', help='keep existing wheels')
    args = parser.parse_args(argv)
    if not REQUIREMENTS.is_file():
        raise SystemExit(f'missing {REQUIREMENTS}')
    WHEELHOUSE.mkdir(parents=True, exist_ok=True)
    if not args.keep:
        for old in WHEELHOUSE.glob('*.whl'):
            old.unlink()
    command = [
        sys.executable, '-m', 'pip', 'download',
        '--dest', str(WHEELHOUSE),
        '--only-binary=:all:',
        '--platform', PLATFORM,
        '--python-version', PYTHON_VERSION,
        '--implementation', 'cp',
        '--abi', 'cp313',
        '--abi', 'abi3',
        '--abi', 'none',
        '--no-cache-dir',
        '-r', str(REQUIREMENTS),
    ]
    print('Running:', ' '.join(command))
    subprocess.run(command, check=True)

    wheels = sorted(WHEELHOUSE.glob('*.whl'))
    if not wheels:
        raise SystemExit('No wheels were downloaded.')
    entries: list[tuple[str, str, str, str]] = []
    names: set[str] = set()
    for wheel in wheels:
        validate_wheel(wheel)
        name, version = wheel_metadata(wheel)
        if not name or not version:
            raise SystemExit(f'Incomplete metadata in {wheel.name}')
        normalized = name.lower().replace('_', '-')
        names.add(normalized)
        entries.append((normalized, name, version, sha256(wheel)))
    missing = REQUIRED - names
    if missing:
        raise SystemExit('Missing required wheels: ' + ', '.join(sorted(missing)))
    entries.sort(key=lambda item: item[0])
    lines = [
        '# Generated by tools/fetch_wheels.py',
        f'# Target: CPython {PYTHON_VERSION}, {PLATFORM} (Synology DSM 7.2, r1000)',
        '# Install offline with: pip install --no-index --find-links wheelhouse --require-hashes -r requirements-dsm.lock',
        '',
    ]
    for _, name, version, digest in entries:
        lines.append(f'{name}=={version} --hash=sha256:{digest}')
    LOCK.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    total = sum(wheel.stat().st_size for wheel in wheels)
    print(f'{len(wheels)} wheels, {total / (1024 * 1024):.1f} MiB')
    print(f'wrote {LOCK.relative_to(ROOT)}')
    for wheel in wheels:
        print(f'  {wheel.name}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
